/** Text blocks → clean paragraphs with their heading. Drops what is not running text. */
export function cleanBlocks(blocks) {
  const out = [];
  let heading = '';
  for (const b of blocks || []) {
    const type = b.type === 'heading' ? 'heading' : (b.type === 'p' || b.type === 'paragraph' || b.type === 'text') ? 'p' : b.type === 'list' ? 'list' : '';
    if (!type) continue;                                          // tables, code, captions: not prose
    let text = type === 'list' ? (b.items || []).map((i) => (typeof i === 'string' ? i : i.text || '')).join(' ') : String(b.text || '');
    text = normalizeText(text).replace(/<\|[^|>]{0,24}\|>/g, ' ').replace(/\[\s*(?:\d+|citation needed|edit|note \d+)\s*\]/gi, '').replace(/https?:\/\/\S+/g, '').replace(/[ \t]{2,}/g, ' ').trim();
    if (!text) continue;
    if (type === 'heading') { heading = text.length <= 90 ? text.replace(/\s*\[edit\]$/i, '') : ''; continue; }
    if (/^(references|external links|see also|further reading|notes|bibliography|citations|sources|navigation menu)$/i.test(heading)) continue;
    if (text.length < 25 && !/[.!?]$/.test(text)) continue;       // menu items, labels
    if (/^(copyright|©|all rights reserved|cookie|privacy policy|terms of (use|service)|subscribe|share this|follow us|advertisement)/i.test(text)) continue;
    out.push({ h: heading, text });
  }
  return out;
}

/**
 * Quality, spam and poisoning checks on one cleaned document.
 * @returns {{ok: boolean, reasons: string[], score: number, stats: object}}  score in 0..1 (text quality only)
 */
export function inspectText(paras, cfg, { title = '' } = {}) {
  const text = paras.map((p) => p.text).join('\n');
  const reasons = [];
  const chars = text.length;
  const words = text.match(/\p{L}+/gu) || [];
  const letters = (text.match(/\p{L}/gu) || []).length;
  const digits = (text.match(/\d/g) || []).length;
  const upper = (text.match(/\p{Lu}/gu) || []).length;
  const sentences = splitSentences(text);
  const stats = { chars, words: words.length, sentences: sentences.length, paragraphs: paras.length };
  if (chars < cfg.minChars) reasons.push(`too short (${chars} characters)`);
  if (chars > cfg.maxChars) reasons.push('too long');
  stats.alpha = +(letters / Math.max(1, chars)).toFixed(3);
  stats.digits = +(digits / Math.max(1, chars)).toFixed(3);
  stats.upper = +(upper / Math.max(1, letters)).toFixed(3);
  if (stats.alpha < 0.6) reasons.push(`mostly not text (letters ${Math.round(stats.alpha * 100)}%)`);
  if (stats.upper > 0.3) reasons.push('mostly capital letters');
  const meanWord = words.reduce((a, w) => a + w.length, 0) / Math.max(1, words.length);
  stats.meanWord = +meanWord.toFixed(2);
  if (meanWord < 3 || meanWord > 9) reasons.push('unusual word lengths');
  const meanSent = words.length / Math.max(1, sentences.length);
  stats.meanSentence = +meanSent.toFixed(1);
  if (meanSent > 80) reasons.push('no sentence structure');
  // keyword stuffing and loops: the same content word or the same sentence over and over
  const freq = new Map();
  const own = new Set((String(title).toLowerCase().match(/\p{L}+/gu) || []));       // a text about Nepal says "Nepal" often: that is its subject, not stuffing
  for (const w of words) { const k = w.toLowerCase(); if (k.length > 3 && !EN_WORDS.has(k) && !own.has(k)) freq.set(k, (freq.get(k) || 0) + 1); }
  const top = Math.max(0, ...freq.values());
  stats.topWordShare = +(top / Math.max(1, words.length)).toFixed(3);
  if (words.length > 200 && stats.topWordShare > 0.08) reasons.push('one word repeated very often (keyword stuffing)');
  const seen = new Map();
  for (const s of sentences) { const k = s.toLowerCase().replace(/\W+/g, ' ').trim(); if (k.length > 30) seen.set(k, (seen.get(k) || 0) + 1); }
  const repeated = [...seen.values()].reduce((a, n) => a + (n > 1 ? n - 1 : 0), 0);
  stats.repeatedSentences = +(repeated / Math.max(1, sentences.length)).toFixed(3);
  if (sentences.length > 10 && stats.repeatedSentences > 0.2) reasons.push('the same sentences are repeated');
  const spam = (text.match(SPAM) || []).length;
  stats.spamPer1k = +(spam / Math.max(1, words.length) * 1000).toFixed(2);
  if (spam >= 3 && stats.spamPer1k > 2) reasons.push('advertising or spam wording');
  const bangs = (text.match(/!/g) || []).length / Math.max(1, sentences.length);
  if (bangs > 0.5 && sentences.length > 8) reasons.push('promotional tone');
  const inj = INJECTION.exec(text);
  if (inj) reasons.push(`contains text addressed to an AI system ("${inj[0].slice(0, 40)}")`);
  if (GENERATED.test(text)) reasons.push('appears to be machine-generated text');
  let score = 1;
  score -= Math.min(0.3, stats.repeatedSentences);
  score -= Math.min(0.2, stats.spamPer1k / 10);
  score -= stats.alpha < 0.72 ? 0.15 : 0;
  score -= meanSent < 6 ? 0.15 : 0;
  score -= chars < 1200 ? 0.1 : 0;
  return { ok: reasons.length === 0, reasons, score: Math.max(0, +score.toFixed(3)), stats };
}

/** Sentences fit for training and for use as evidence: complete, of sensible length, no leftovers of removed markup. */
export function goodSentences(text) {
  return splitSentences(text).map((s) => s.trim()).filter((s) => s.length >= 30 && s.length <= 420 && /^[\p{Lu}\d"“(]/u.test(s) && /[.!?"”)]$/.test(s) && !s.includes('⟨') && (s.match(/\p{L}/gu) || []).length / s.length > 0.6);
}
