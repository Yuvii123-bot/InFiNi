/** Rough language check: share of the commonest English words, and of Latin letters. Returns 'en', 'other' or 'und'. */
export function languageOf(text) {
  const sample = text.slice(0, 6000);
  const words = sample.toLowerCase().match(/\p{L}+/gu) || [];
  if (words.length < 30) return 'und';
  let hit = 0; for (const w of words) if (EN_WORDS.has(w)) hit++;
  const letters = sample.match(/\p{L}/gu) || [];
  const latin = sample.match(/[A-Za-z]/g) || [];
  if (latin.length / Math.max(1, letters.length) < 0.85) return 'other';
  return hit / words.length >= 0.22 ? 'en' : 'other';
}

/** 64-bit SimHash over word 4-grams, as two unsigned 32-bit halves. Near-identical texts differ in a few bits only. */
export function simhash(text) {
  const toks = tokenize(text);
  const v = new Int32Array(64);
  const n = Math.max(1, toks.length - 3);
  for (let i = 0; i < n; i++) {
    const h = crypto.createHash('md5').update(toks.slice(i, i + 4).join(' ')).digest();
    for (let b = 0; b < 64; b++) v[b] += (h[b >> 3] >> (b & 7)) & 1 ? 1 : -1;
  }
  let hi = 0, lo = 0;
  for (let b = 0; b < 32; b++) { if (v[b] > 0) lo |= (1 << b); if (v[b + 32] > 0) hi |= (1 << b); }
  return [hi >>> 0, lo >>> 0];
}
